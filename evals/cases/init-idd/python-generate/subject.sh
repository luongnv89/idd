#!/usr/bin/env bash
# init-idd stand-in (python-generate): a fresh .idd.yml for a Python repo.
#
# Step 1 runs the REAL gi-stack-detect.py on the fixture repository. Step 3
# substitutes its results into a compact copy of the template's placeholder
# lines, writes .idd.yml, and runs *Validate the written config*: the file
# parses, no placeholder token survives, and `platform` is set. The merge
# strategy check then makes its two read-only gh reads. The written file must
# equal expected/idd.yml, which tests/test-eval-triage-autopilot-357.sh feeds
# to the real gi-config.py against the full schema. No repository setting is
# changed and no tracker write is made.
set -euo pipefail

: "${EVAL_OUT:?EVAL_OUT is required}"
: "${EVAL_CASE_DIR:?EVAL_CASE_DIR is required}"
: "${EVAL_SCRIPTS_DIR:?EVAL_SCRIPTS_DIR is required}"

# The fixture is copied without history: make it the git repository the
# skill requires, with the GitHub remote the merge check reads its name from.
git init -q -b main
git add -A
git remote add origin https://github.com/eval/notes-api.git

python3 "$EVAL_SCRIPTS_DIR/gi-stack-detect.py" --root . > "$EVAL_OUT/detect.json"

OUT="$EVAL_OUT" EXPECTED="$EVAL_CASE_DIR/expected/idd.yml" python3 - <<'PY'
import json
import os
import re
import sys

out = os.environ["OUT"]
detect = json.load(open(os.path.join(out, "detect.json"), encoding="utf-8"))
if detect["unresolved"]:
    sys.exit(f"stand-in expects a fully detected fixture, unresolved: {detect['unresolved']}")


def touch(name, text=""):
    with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
        fh.write(text + "\n")


TEMPLATE = """\
# IDD Stack configuration
# Generated by /init-idd
# Detected: {language} | {framework} | {test_runner} | {repo_size} repo ({file_count} files)

# Platform for issue management
platform: github

# Issue creation and normalization settings
issue:
  auto_normalize: true
{template_note}  template: default

# Resolution pipeline settings
resolve:
  # {test_runner} found in {test_runner_source}
  auto_test: {true_or_false}
  test_timeout: {timeout_value}

# Triage settings
triage:
  stale_threshold_days: {stale_value}

# Review settings
review:
  auto_merge: false
  merge_method: squash

# Autopilot settings
autopilot:
  mode: balanced
"""
PLACEHOLDER = re.compile(r"\{(language|framework|test_runner|repo_size|file_count|true_or_false|timeout_value|stale_value)\}")

note = ""
if detect["issue_templates"]:
    note = (f"  # Note: .github/ISSUE_TEMPLATE/ found ({detect['issue_templates']} templates)\n"
            '  # Set template to ".github/ISSUE_TEMPLATE" to use your existing templates\n')
values = {
    "language": detect["language"], "framework": detect["framework"],
    "test_runner": detect["test_runner"], "test_runner_source": detect["test_runner_source"],
    "repo_size": detect["repo_size"], "file_count": str(detect["file_count"]),
    "true_or_false": "true" if detect["derived"]["auto_test"] else "false",
    "timeout_value": str(detect["derived"]["test_timeout"]),
    "stale_value": str(detect["derived"]["stale_threshold_days"]),
    "template_note": note,
}


def render(skip=()):
    text = TEMPLATE
    for key, value in values.items():
        if key not in skip:
            text = text.replace("{" + key + "}", value)
    return text


def problems(text):
    """*Validate the written config*: parse, no placeholder left, platform set.

    The parse is a stdlib check of the template's YAML subset (comments,
    two-space nesting, `key: scalar` or `key:` opening a block), so the
    stand-in needs no PyYAML; the real gi-config.py parses expected/idd.yml in
    the test suite.
    """
    bad = []
    top = set()
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.fullmatch(r"( {0,2})([a-z_]+):(?: (\S.*))?", line)
        if not m:
            bad.append(f"line {number} does not parse")
            continue
        if not m.group(1):
            top.add(m.group(2))
    if PLACEHOLDER.search(text):
        bad.append("placeholder survived")
    if "platform" not in top:
        bad.append("platform missing")
    return bad


written = render()
with open(".idd.yml", "w", encoding="utf-8") as fh:
    fh.write(written)
reread = open(".idd.yml", encoding="utf-8").read()
if problems(reread):
    sys.exit(f"generated config failed validation: {problems(reread)}")
touch("validated.txt")
with open(os.path.join(out, "idd.yml"), "w", encoding="utf-8") as fh:
    fh.write(reread)
if reread == open(os.environ["EXPECTED"], encoding="utf-8").read():
    touch("matches-expected.txt")

# The validator must refuse what it exists to catch.
broken = [render(skip=("timeout_value",)), render().replace("platform: github\n", "")]
if any(not problems(text) for text in broken):
    touch("broken-config-accepted.txt")
PY

# Merge strategy check: two read-only reads, judged against review.merge_method.
gh auth status >/dev/null
REMOTE="$(git remote get-url origin)"
SLUG="${REMOTE#https://github.com/}"
SLUG="${SLUG%.git}"
gh repo view --json mergeCommitAllowed,squashMergeAllowed,rebaseMergeAllowed > "$EVAL_OUT/strategy.json"
gh api "repos/$SLUG" --jq '{squash_merge_commit_message, merge_commit_message}' > "$EVAL_OUT/message-source.json"

OUT="$EVAL_OUT" python3 - <<'PY'
import json
import os
import re

out = os.environ["OUT"]
config = open(".idd.yml", encoding="utf-8").read()
method = re.search(r"(?m)^review:\n(?:  .*\n|\s*\n)*?  merge_method: (\S+)", config).group(1)
strategy = json.load(open(os.path.join(out, "strategy.json"), encoding="utf-8"))
source = json.load(open(os.path.join(out, "message-source.json"), encoding="utf-8"))
allowed = [m for m, key in (("squash", "squashMergeAllowed"), ("merge", "mergeCommitAllowed"),
                            ("rebase", "rebaseMergeAllowed")) if strategy[key]]
ok = method in allowed
row = f"✓ {method} allowed" if ok else f"⚠ {method} not allowed (allowed: {', '.join(allowed)})"
open(os.path.join(out, f"merge-method-{'allowed' if ok else 'not-allowed'}.txt"), "w").write(row + "\n")
detect = json.load(open(os.path.join(out, "detect.json"), encoding="utf-8"))
with open(os.path.join(out, "report.txt"), "w", encoding="utf-8") as fh:
    fh.write(
        "◆ Init IDD — setup complete\n"
        "  Result:            DONE — .idd.yml generated and validated\n"
        f"  Language:          ✓ {detect['language']} (from {detect['language_source']})\n"
        f"  Framework:         ✓ {detect['framework']} (from {detect['framework_source']})\n"
        f"  Test runner:       ✓ {detect['test_runner']} (from {detect['test_runner_source']})\n"
        f"  Repo size:         ✓ {detect['repo_size']} ({detect['file_count']} files, via {detect['file_count_source']})\n"
        "  Validation:        ✓ parses, no placeholders left, platform set\n"
        f"  Merge settings:    {row}; squash message source {source['squash_merge_commit_message']}\n"
        "  Evidence:          gi-stack-detect exit 0; re-read with the stand-in parser\n"
        "  Uncertainty:       values from marker files; no test command run\n"
        "  Decision:          No approval needed.\n"
        "  Next action: review and commit .idd.yml, then /issue-creator\n"
    )
PY

# Nothing but .idd.yml was added to the repository.
if git diff --quiet && [ "$(git ls-files --others --exclude-standard)" = ".idd.yml" ]; then
  : > "$EVAL_OUT/only-config-written.txt"
fi
